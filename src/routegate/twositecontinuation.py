def data_root(paths: Optional[Mapping[str, str]] = None) -> Path:
    """The private data root, from the machine-local path file.

    The four pinned artifacts are addressed relative to it, so no absolute path
    to prompt-bearing data appears in this package.
    """
    if paths is None:
        from .data import load_local_paths
        paths = load_local_paths()
    dataset = paths.get("dataset")
    if not dataset:
        raise ContinuationError(
            "configs/paths.local.json declares no dataset path, so the data "
            "root cannot be located")
    root = Path(dataset).parent.parent.parent
    if not root.is_dir():
        raise ContinuationError(f"{root} is not a directory")
    return root


def pinned_inputs(root: Optional[Path] = None) -> Dict[str, Dict[str, str]]:
    """The four pinned artifacts, with their paths resolved against the root."""
    root = root or data_root()
    return {
        "master": {"path": str(root / MASTER_PATH), "sha256": MASTER_SHA256},
        "master_run_config": {"path": str(root / MASTER_RUN_CONFIG_PATH),
                              "sha256": MASTER_RUN_CONFIG_SHA256},
        "phase1_records": {"path": str(root / PHASE1_RECORDS_PATH),
                           "sha256": PHASE1_RECORDS_SHA256},
        "v1_records": {"path": str(root / V1_RECORDS_PATH),
                       "sha256": V1_RECORDS_SHA256},
    }


def verify_pinned_inputs(root: Optional[Path] = None,
                         checks: Optional[Checklist] = None
                         ) -> Dict[str, Dict[str, str]]:
    """Every pinned artifact is byte-for-byte the one this path was built on."""
    checks = checks or Checklist("two_site_continuation")
    inputs = pinned_inputs(root)
    for name, entry in sorted(inputs.items()):
        path = Path(entry["path"])
        checks.require(f"{name}_exists", path.is_file(),
                       f"{path} does not exist")
        actual = sha256_file(path)
        checks.require(
            f"{name}_sha256", actual == entry["sha256"],
            f"{path.name} hashes to {actual}, this continuation is pinned to "
            f"{entry['sha256']}. A different artifact is different evidence; "
            f"it is refused, not adopted.")
    return inputs


# ======================================================= the referenced baseline
def read_master(path: Path | str) -> Dict[str, Dict[str, str]]:
    """The master, indexed by row id. Read once, never written."""
    with open(path, newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    if len(rows) != EXPECTED_ROWS:
        raise ContinuationError(
            f"the master holds {len(rows)} row(s), expected {EXPECTED_ROWS}")
    indexed: Dict[str, Dict[str, str]] = {}
    for row in rows:
        if row["row_id"] in indexed:
            raise ContinuationError(
                f"the master lists {row['row_id']} more than once")
        indexed[row["row_id"]] = row
    return indexed


def verify_referenced_baseline(master: Mapping[str, Mapping[str, str]],
                               corpus_rows: Sequence[Mapping[str, str]],
                               phase1_records: Sequence[Mapping[str, Any]],
                               v1_records: Sequence[Mapping[str, Any]],
                               checks: Optional[Checklist] = None,
                               expected_rows: int = EXPECTED_ROWS,
                               expected_phase1: int = EXPECTED_PHASE1_BASELINES,
                               expected_v1: int = EXPECTED_REUSABLE_CANDIDATES,
                               ) -> Dict[str, Any]:
    """The master's 480 before-responses are a usable referenced baseline.

    Three separate questions, answered separately because they fail
    differently: does the master describe the corpus this package gates on;
    does an independent regeneration of part of it agree byte for byte; and how
    much of it is corroborated that way rather than by provenance alone.

    The three expected counts are parameters with the production values as
    their defaults, so a test can exercise the byte comparison on a small frame
    without the count gates short-circuiting it. No caller in this path passes
    anything but the defaults.
    """
    checks = checks or Checklist("two_site_continuation")
    corpus = {row["row_id"]: row for row in corpus_rows}

    # -- 1. the master IS the corpus ------------------------------------
    checks.require("master_row_count", len(master) == expected_rows,
                   f"{len(master)} master row(s), expected {expected_rows}")
    checks.require("corpus_row_count", len(corpus) == expected_rows,
                   f"{len(corpus)} corpus row(s), expected {expected_rows}")
    missing = sorted(set(master) - set(corpus))
    added = sorted(set(corpus) - set(master))
    checks.require("master_ids_are_the_corpus_ids", not missing and not added,
                   f"{len(missing)} master row(s) absent from the corpus, "
                   f"{len(added)} corpus row(s) absent from the master")
    wrong_class = sorted(rid for rid in master
                         if master[rid]["frozen_class"]
                         != corpus[rid]["final_ebh"])
    checks.require(
        "master_classes_match_the_corpus", not wrong_class,
        f"{len(wrong_class)} row(s) carry a different class in the master than "
        f"in the corpus, first {wrong_class[:3]}")
    wrong_text = sorted(rid for rid in master
                        if master[rid]["prompt_text"]
                        != corpus[rid]["prompt_text"])
    checks.require(
        "master_prompt_bytes_match_the_corpus", not wrong_text,
        f"{len(wrong_text)} row(s) carry different prompt bytes, first "
        f"{wrong_text[:3]}")
    wrong_digest = sorted(rid for rid in master
                          if sha256_text(master[rid]["prompt_text"])
                          != corpus[rid]["prompt_sha256"])
    checks.require(
        "master_prompt_digests_recompute", not wrong_digest,
        f"{len(wrong_digest)} row(s) whose master prompt does not hash to the "
        f"corpus digest")
    empty = sorted(rid for rid in master
                   if not master[rid].get(MASTER_BASELINE_COLUMN))
    checks.require(
        "every_master_row_carries_a_baseline_response", not empty,
        f"{len(empty)} master row(s) have an empty {MASTER_BASELINE_COLUMN}")

    # -- 2. independent reproduction, where one exists ------------------
    def _compare(records, label, expected_count=None):
        baselines = [r for r in records if r.get("arm_id") == BASELINE_ARM]
        if expected_count is not None:
            checks.require(
                f"{label}_baseline_count", len(baselines) == expected_count,
                f"{len(baselines)} {label} baseline record(s), expected "
                f"{expected_count}")
        absent = [r["row_id"] for r in baselines if r["row_id"] not in master]
        checks.require(f"{label}_rows_are_master_rows", not absent,
                       f"{len(absent)} {label} baseline row(s) are not in the "
                       f"master")
        differing = [r["row_id"] for r in baselines
                     if r.get("response_text")
                     != master[r["row_id"]][MASTER_BASELINE_COLUMN]]
        checks.require(
            f"{label}_baselines_are_byte_identical_to_the_master", not differing,
            f"{len(differing)} of {len(baselines)} {label} baseline response(s) "
            f"differ from the master's {MASTER_BASELINE_COLUMN}, first "
            f"{differing[:3]}. A referenced baseline that does not reproduce is "
            f"not a baseline, and the reference is refused rather than "
            f"preferred over the regeneration.")
        digests = [r["row_id"] for r in baselines
                   if r.get("prompt_sha256")
                   != sha256_text(master[r["row_id"]]["prompt_text"])]
        checks.require(f"{label}_prompt_digests_match", not digests,
                       f"{len(digests)} {label} prompt digest mismatch(es)")
        return {rec["row_id"] for rec in baselines}

    phase1_rows = _compare(phase1_records, "phase1", expected_phase1)
    v1_rows = _compare(v1_records, "interrupted_v1", expected_v1)

    reproduced = phase1_rows | v1_rows
    checks.record(
        "referenced_baselines_independently_reproduced", True,
        f"{len(reproduced)} of {expected_rows} master baselines are "
        f"byte-identical to an independent regeneration "
        f"({len(phase1_rows)} phase-1 + {len(v1_rows)} interrupted); the "
        f"remaining {expected_rows - len(reproduced)} rest on the master's own "
        f"provenance and its matching configuration digests")
    return {
        "rows": expected_rows,
        "independently_reproduced": sorted(reproduced),
        "independently_reproduced_count": len(reproduced),
        "referenced_on_provenance_only": expected_rows - len(reproduced),
        "phase1_reproduced": len(phase1_rows),
        "interrupted_v1_reproduced": len(v1_rows),
        "generated_by_this_run": 0,
        "source": MASTER_PATH,
        "source_sha256": MASTER_SHA256,
        "column": MASTER_BASELINE_COLUMN,
        "provenance": "the master's own run configuration records "
                      "before_source.regenerated: false and pins the same "
                      "corpus digest this package gates on. These responses "
                      "are REFERENCED, not generated here.",
        "after_response_text_is_not_used": "the master's after-responses come "
                                           "from consensus23_global_frozen, a "
                                           "different actuator at a different "
                                           "direction. Only the before column "
                                           "is read.",
    }


# ============================================== the deterministic row order
def deterministic_row_order(rows: Sequence[Mapping[str, str]]) -> List[str]:
    """The one order this validation plans work in: row id, ascending.

    Sorted rather than taken from corpus order so two machines shard the same
    480 rows the same way, and a resume file is comparable to the run that
    produced it.
    """
    ids = sorted(str(row["row_id"]) for row in rows)
    if len(set(ids)) != len(ids):
        duplicated = sorted({r for r in ids if ids.count(r) > 1})
        raise ContinuationError(
            f"{len(ids) - len(set(ids))} duplicated row id(s) {duplicated[:3]}")
    return ids


def shard_rows(ordered: Sequence[str], index: int, count: int) -> List[str]:
    """Shard ``index`` of ``count``, as a genuine partition of ``ordered``.

    Contiguous, one-based, and exhaustive: every row lands in exactly one
    shard and no row lands in two. ``assert_shards_partition`` proves that over
    the whole set rather than trusting this arithmetic.
    """
    if not isinstance(index, int) or not isinstance(count, int):
        raise ContinuationError("shard index and count are integers")
    if count < 1:
        raise ContinuationError(f"--shard-count is {count}; it is at least 1")
    if not 1 <= index <= count:
        raise ContinuationError(
            f"--shard-index is {index}; it runs 1..{count} inclusive")
    total = len(ordered)
    base, extra = divmod(total, count)
    start = (index - 1) * base + min(index - 1, extra)
    size = base + (1 if index <= extra else 0)
    return list(ordered[start:start + size])


def assert_shards_partition(ordered: Sequence[str], count: int,
                            checks: Optional[Checklist] = None
                            ) -> Dict[str, Any]:
    """Every shard together is the whole set, once. Proved, not asserted."""
    checks = checks or Checklist("two_site_continuation")
    shards = [shard_rows(ordered, i, count) for i in range(1, count + 1)]
    flat = [rid for shard in shards for rid in shard]
    checks.require(
        "shards_cover_every_row", sorted(flat) == sorted(ordered),
        f"the {count} shard(s) cover {len(set(flat))} distinct row(s) of "
        f"{len(ordered)}")
    checks.require(
        "shards_do_not_overlap", len(flat) == len(set(flat)) == len(ordered),
        f"{len(flat) - len(set(flat))} row(s) appear in more than one shard")
    sizes = [len(s) for s in shards]
    checks.require(
        "shards_are_balanced", max(sizes) - min(sizes) <= 1,
        f"shard sizes {sizes} differ by more than one row")
    return {"count": count, "sizes": sizes, "rows": len(ordered)}


# ================================================ the reusable candidate records
#: Every field a reused candidate record must carry unchanged. A record that
#: differs in any of them was produced by a different run, whatever its arm
#: says.
LOCKED_FIELDS: Tuple[str, ...] = (
    "protocol", "arm_id", "alpha_R", "alpha_S", "intervention_type",
    "budget_reference", "states", "historical_layers", "model", "revision",
    "generation_config_sha256", "tokenizer_config_sha256",
    "chat_template_sha256", "direction_bank_sha256", "dataset_sha256", "smoke",
)


def validate_candidate_record(record: Mapping[str, Any],
                              expected: Mapping[str, Any],
                              corpus: Mapping[str, Mapping[str, str]],
                              where: str) -> None:
    """One candidate record is what it claims to be, or it is refused.

    Checked in full rather than by arm id: a record carrying the right arm
    name and the wrong direction, sites, strength or prompt is the failure this
    exists to catch, and it looks entirely well formed.
    """
    for field in LOCKED_FIELDS:
        if field not in expected:
            continue
        want, got = expected[field], record.get(field)
        if isinstance(want, (list, tuple)):
            want, got = list(want), list(got or [])
        if got != want:
            raise ContinuationError(
                f"{where}: {field} is {got!r} and this run is {want!r}. A "
                f"record produced under different settings is not reused; it "
                f"is refused, and the row is regenerated.")
    if record.get("arm_id") != CANDIDATE_ARM_ID:
        raise ContinuationError(
            f"{where}: arm {record.get('arm_id')!r}, expected "
            f"{CANDIDATE_ARM_ID!r}")
    if list(record.get("states") or []) != list(CANDIDATE_STATES):
        raise ContinuationError(
            f"{where}: states {record.get('states')!r}, expected "
            f"{list(CANDIDATE_STATES)} (historical blocks "
            f"{list(CANDIDATE_BLOCKS)})")
    if 34 in (record.get("states") or []) or 33 in (
            record.get("historical_layers") or []):
        raise ContinuationError(
            f"{where}: historical block 33 / package state 34 is present. That "
            f"site failed the one-pass budget test and is not in this arm.")
    if record.get("status") != "ok":
        raise ContinuationError(
            f"{where}: status {record.get('status')!r}. Only a completed "
            f"record is reused; an error is regenerated, never inherited.")
    if record.get("error_message"):
        raise ContinuationError(
            f"{where}: carries error_message {record['error_message']!r}")
    hooks_expected = record.get("hooks_expected")
    hooks_fired = record.get("hooks_fired")
    if hooks_expected != len(CANDIDATE_STATES) or hooks_fired != hooks_expected:
        raise ContinuationError(
            f"{where}: {hooks_fired} hook(s) fired of {hooks_expected} "
            f"expected; this arm edits {len(CANDIDATE_STATES)} sites and a "
            f"record whose edit did not fire is not a steered record.")
    rid = record.get("row_id")
    if rid not in corpus:
        raise ContinuationError(f"{where}: {rid!r} is not a corpus row")
    if record.get("prompt_sha256") != corpus[rid]["prompt_sha256"]:
        raise ContinuationError(
            f"{where}: prompt digest {record.get('prompt_sha256')!r} is not "
            f"the corpus digest {corpus[rid]['prompt_sha256']!r}")
    if record.get("row_class") != corpus[rid]["final_ebh"]:
        raise ContinuationError(
            f"{where}: class {record.get('row_class')!r}, corpus says "
            f"{corpus[rid]['final_ebh']!r}")
    per_state = record.get("per_state") or {}
    if sorted(int(s) for s in per_state) != list(CANDIDATE_STATES):
        raise ContinuationError(
            f"{where}: per_state covers {sorted(per_state)}, expected "
            f"{list(CANDIDATE_STATES)}")
    for state, entry in per_state.items():
        digest = entry.get("repair_direction_sha256")
        if not digest or len(str(digest)) != 64:
            raise ContinuationError(
                f"{where}: state {state} records no repair direction digest")


def load_reusable_candidates(path: Path | str,
                             expected: Mapping[str, Any],
                             corpus: Mapping[str, Mapping[str, str]],
                             checks: Optional[Checklist] = None
                             ) -> Dict[str, Dict[str, Any]]:
    """The interrupted run's completed candidates, fully validated.

    The file is pinned by digest before it is opened, so this cannot silently
    pick up a fourth record added later; the row-id list is the second witness.
    """
    checks = checks or Checklist("two_site_continuation")
    records = read_jsonl_strict(path)
    candidates = [r for r in records if r.get("arm_id") == CANDIDATE_ARM_ID]
    checks.require(
        "interrupted_candidate_count",
        len(candidates) == EXPECTED_REUSABLE_CANDIDATES,
        f"{len(candidates)} candidate record(s) in the interrupted run, "
        f"expected {EXPECTED_REUSABLE_CANDIDATES}")
    rows = tuple(sorted(r["row_id"] for r in candidates))
    checks.require(
        "interrupted_candidate_rows_are_the_pinned_ones",
        rows == tuple(sorted(REUSABLE_CANDIDATE_ROWS)),
        f"the interrupted run completed {list(rows)}, this continuation pins "
        f"{list(REUSABLE_CANDIDATE_ROWS)}")
    for record in candidates:
        validate_candidate_record(
            record, expected, corpus,
            f"reused record {record['row_id']}")
    checks.record(
        "interrupted_candidates_validated", True,
        f"{len(candidates)} record(s) match on {len(LOCKED_FIELDS)} locked "
        f"field(s), prompt digest, class, sites, direction digest, status and "
        f"hook count")
    return {r["row_id"]: r for r in candidates}


def read_jsonl_strict(path: Path | str) -> List[Dict[str, Any]]:
    """Every record, or a refusal. A truncated line is never skipped.

    ``dualsteer.read_records`` tolerates a partial final line so a killed job
    can resume. Here the file is either complete evidence or it is not used,
    so a truncated line anywhere -- including the end -- is an error.
    """
    path = Path(path)
    if not path.exists():
        return []
    out: List[Dict[str, Any]] = []
    lines = path.read_text(encoding="utf-8").splitlines()
    for number, line in enumerate(lines, start=1):
        if not line.strip():
            continue
        try:
            out.append(json.loads(line))
        except Exception as exc:
            raise ContinuationError(
                f"{path}:{number} is not valid JSON: {exc}. A truncated line "
                f"is a crash, not a record, and this file is read as evidence "
                f"rather than resumed.") from exc
    return out


# ================================================================ the restart
def validate_existing_shard(path: Path | str,
                            allowed_rows: Sequence[str],
                            expected: Mapping[str, Any],
                            corpus: Mapping[str, Mapping[str, str]],
                            checks: Optional[Checklist] = None
                            ) -> Dict[str, Dict[str, Any]]:
    """Records already in this shard's file are validated before being skipped.

    A restart that trusted its own output would inherit whatever the crash
    left: a duplicate, a row from another shard, an error record, or a record
    written under settings that have since moved. Each is refused by name.
    """
    checks = checks or Checklist("two_site_continuation")
    records = read_jsonl_strict(path)
    if not records:
        checks.record("existing_shard_records", True, "none; a fresh shard")
        return {}

    allowed = set(allowed_rows)
    seen: Dict[str, Dict[str, Any]] = {}
    for index, record in enumerate(records):
        where = f"{Path(path).name}:{index}"
        rid = record.get("row_id")
        if rid in seen:
            raise ContinuationError(
                f"{where}: {rid} appears more than once. One row is generated "
                f"once; a duplicate is refused rather than deduplicated, "
                f"because the two may differ.")
        if rid not in allowed:
            raise ContinuationError(
                f"{where}: {rid} is not one of this shard's "
                f"{len(allowed)} row(s). A record from another shard in this "
                f"file means two processes shared it.")
        validate_candidate_record(record, expected, corpus, where)
        seen[rid] = record
    checks.record(
        "existing_shard_records", True,
        f"{len(seen)} record(s) validated and will be skipped; "
        f"{len(allowed) - len(seen)} remain")
    return seen


def assert_shard_is_not_complete(done: Mapping[str, Any],
                                 allowed_rows: Sequence[str]) -> None:
    """A finished shard is not re-entered, so a completed run cannot be rerun."""
    if len(done) >= len(allowed_rows) and allowed_rows:
        raise ContinuationError(
            f"this shard's {len(allowed_rows)} row(s) are already complete and "
            f"validated. A finished shard is not re-run: its records are the "
            f"result. Consolidate instead, or name a new output directory.")


