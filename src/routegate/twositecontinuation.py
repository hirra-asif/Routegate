"""Continuing the two-site causal validation after an interrupted run.

The first attempt wrote six records -- three baseline, three candidate -- and
stopped. Its runner could not be restarted, for two reasons found by audit and
corrected only here, in a new versioned path:

* ``claim_output_dir`` refused a non-empty output directory *before* ``--resume``
  was ever consulted, and a resumable directory is non-empty by definition. So
  ``--resume`` was unreachable.
* ``--shard-index`` and ``--shard-count`` were declared and never read. Every
  shard would have generated all 480 rows, and the shards would have collided
  rather than partitioned.

Neither is repaired in place. ``run_two_site_validation.py`` and the records it
wrote stay exactly as they are: they are the evidence of what happened, and
evidence is not edited to make a later run tidier.

What the continuation does differently
--------------------------------------
It generates **candidates only**. The 480 baseline responses are *referenced*
from the frozen static-steering master, whose own run configuration records
``before_source.regenerated: false`` and pins the same corpus digest this
package gates on. That reference is corroborated, not assumed:

* all 480 master row ids, classes and prompt bytes are revalidated against the
  frozen development corpus;
* 302 phase-1 baseline responses are byte-identical to the master's;
* the interrupted run's 3 B baselines are byte-identical to the master's.

305 of the 480 are therefore independently reproduced. The remaining 175 -- B
rows, which phase 1 never steered -- rest on the master's own provenance and
its matching model, revision, tokenizer, chat template and decoding digests.
That distinction is recorded rather than smoothed over, and no manifest in this
path claims a baseline was generated by it.

The master's ``after_response_text`` is NOT usable here. It was produced by
``consensus23_global_frozen``, the historical primary actuator, at a different
direction from the validated ``B_d1 - E`` bank this candidate steers. Only
``before_response_text`` is read.

What this module does not do
----------------------------
It generates nothing, judges nothing, trains nothing and loads no model. It
holds the pins, the revalidation, the deterministic row order, the shard
partition and the gates that refuse a record which is not what it claims to be.
"""
