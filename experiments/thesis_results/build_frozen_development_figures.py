def summarise(readings: Dict[str, Any], screen, matrix, probes) -> None:
    say()
    say("  derived system comparison")
    for specification in SYSTEMS:
        reading = readings[specification.system_id]
        cells = "  ".join(
            f"{label} {reading.proportions[label].numerator:>3}/"
            f"{reading.proportions[label].denominator:<3}"
            f"({100.0 * reading.proportions[label].rate:5.1f}%)"
            for label in DEVELOPMENT_CLASSES)
        say(f"    {specification.display_name:<34} {cells}")
    say()
    say(f"  derived phase 2 screen, denominator {screen.denominator}, "
        f"outcome {screen.outcome}")
    for strength in PHASE2_STRENGTHS:
        entry = screen.per_strength[strength]
        say(f"    alpha_S {strength}  recovered "
            f"{screen.recovered[strength].numerator:>2}/{screen.denominator}  "
            f"harmful-alone {screen.harmful_alone[strength].numerator}/"
            f"{screen.denominator}  qualifies "
            f"{'yes' if entry['qualifies'] else 'no'}")
    say()
    say(f"  derived safety-only failure matrix, {len(matrix.labels)} row(s)")
    for label in matrix.labels:
        say(f"    {label}  {matrix.failure_counts[label]} of "
            f"{len(matrix.strengths)} strength(s) failed")
    say()
    say(f"  probe heads, primary state {probes.primary_state} "
        f"(historical block {probes.primary_layer}), {probes.n_folds}-fold "
        f"out-of-fold, no calibration model fitted")
    for head in PROBE_HEADS:
        reading = probes.primary[head]
        say(f"    {head:<7} {PROBE_HEAD_TASKS[head]['task']:<15} "
            f"n={reading.n_scored:>3} (+{reading.n_positive}/"
            f"-{reading.n_negative})  ROC-AUC {reading.roc_auc:.6f}  "
            f"PR-AUC {reading.pr_auc:.6f} (chance {reading.pr_chance:.6f})  "
            f"Brier {reading.brier:.6f}  ECE {reading.ece:.6f}")
    for state in probes.sensitivity_states:
        for head in PROBE_HEADS:
            reading = probes.sensitivity[state][head]
            say(f"    state {state} sensitivity {head:<7} "
                f"ROC-AUC {reading.roc_auc:.6f}  PR-AUC {reading.pr_auc:.6f}  "
                f"Brier {reading.brier:.6f}")


def build(args: argparse.Namespace) -> int:
    checks = Checklist(STAGE)
    created = utc_now()

    sources = resolve_sources(args)
    output_dir = Path(args.output_dir)
    assert_output_directory_is_new(output_dir, checks)

    say(f"[figures] {STAGE}")
    say(f"[figures] output directory {output_dir}")
    for label in sorted(sources):
        say(f"[figures] input {label:<26} {sources[label]}")

    derived = derive_everything(sources, checks)
    digests = derived["digests"]
    readings, screen, matrix = derived["readings"], derived["screen"], derived["matrix"]
    probes = derived["probes"]

    say()
    for label in sorted(digests):
        say(f"[figures] sha256 {label:<26} {digests[label]}")
    summarise(readings, screen, matrix, probes)
    say()
    say(f"[figures] {checks.as_dict()['checks_run']} check(s) run, all passed")

    planned = ([f"{FIGURE_STEMS[i]}.{ext}" for i in (1, 2, 3, 4)
                for ext in ("png", "svg")]
               + ["table_1_system_comparison.csv",
                  "table_2_phase2_causal_screen.csv",
                  "table_3_phase2_failure_matrix.csv",
                  "table_4_probe_heads_oof.csv",
                  "table_5_oof_calibration_bins.csv",
                  "routegate_results_tables.tex",
                  "routegate_results_so_far.md",
                  "provenance_manifest.json",
                  "output_hashes.json"])

    if args.dry_run:
        say()
        say("[figures] dry run: nothing written. Would write "
            f"{len(planned)} file(s) into {output_dir}:")
        for name in planned:
            say(f"[figures]   {name}")
        return 0

    output_dir.mkdir(parents=True, exist_ok=True)
    plt = plotting.configure()
    figures = {
        "figure_1_repair_safety_tradeoff": figure_1(readings, output_dir, plt),
        "figure_2_phase2_causal_screen": figure_2(screen, output_dir, plt),
        "figure_3_safety_only_failure_matrix": figure_3(matrix, screen,
                                                        output_dir, plt),
        "figure_4_oof_reliability": figure_4(probes, output_dir, plt),
    }
    plt.close("all")
    for name, written in figures.items():
        say(f"[figures] wrote {name}: {Path(written['png']).name}, "
            f"{Path(written['svg']).name}")

    rows_1 = table_1_rows(readings)
    write_csv(output_dir / "table_1_system_comparison.csv",
              list(rows_1[0]), rows_1)
    rows_2 = table_2_rows(screen)
    write_csv(output_dir / "table_2_phase2_causal_screen.csv",
              list(rows_2[0]), rows_2)
    rows_3 = table_3_rows(matrix)
    write_csv(output_dir / "table_3_phase2_failure_matrix.csv",
              list(rows_3[0]), rows_3)
    rows_4 = table_4_rows(probes)
    write_csv(output_dir / "table_4_probe_heads_oof.csv",
              list(rows_4[0]), rows_4)
    rows_5 = table_5_rows(probes)
    write_csv(output_dir / "table_5_oof_calibration_bins.csv",
              list(rows_5[0]), rows_5)
    (output_dir / "routegate_results_tables.tex").write_text(
        latex_document(readings, screen, matrix, probes), encoding="utf-8")
    (output_dir / "routegate_results_so_far.md").write_text(
        markdown_document(readings, screen, matrix, probes, digests, sources,
                          created),
        encoding="utf-8")
    say(f"[figures] wrote 5 CSV table(s), routegate_results_tables.tex and "
        f"routegate_results_so_far.md")

    written_before_the_manifest = {
        str(path.relative_to(output_dir)): sha256_file(path)
        for path in sorted(output_dir.rglob("*")) if path.is_file()}

    manifest = {
        "schema": SCHEMA,
        "stage": STAGE,
        "created_utc": created,
        "output_dir": str(output_dir),
        "development_results_only": True,
        "sealed_set_read": False,
        "what_this_is_not": list(DEVELOPMENT_ONLY_STATEMENTS),
        "environment": environment_record(ROUTEGATE_VERSION),
        "git": git_state([
            Path(__file__).resolve(),
            REPO_ROOT / "src" / "routegate" / "thesisresults.py",
            REPO_ROOT / "src" / "routegate" / "plotting.py",
            REPO_ROOT / "configs" / "paths.local.json",
        ]),
        "inputs": {label: {"path": str(sources[label]),
                           "sha256": digests[label],
                           "expected_sha256": EXPECTED_INPUT_DIGESTS[label]}
                   for label in sorted(sources)},
        "derived": {
            "class_sizes": derived["outcomes"].class_sizes(),
            "systems": {specification.system_id:
                        readings[specification.system_id].as_dict()
                        for specification in SYSTEMS},
            "phase2_screen": screen.as_dict(),
            "safety_only_failure_matrix": matrix.as_dict(),
            "probe_heads_oof": probes.as_dict(),
        },
        "system_name_provenance": {
            "summary": RECONSTRUCTION_SUMMARY,
            "statement": RECONSTRUCTION_STATEMENT,
            "by_system": {
                specification.system_id: {
                    "display_name": specification.display_name,
                    "name_standing": specification.name_standing,
                    "denotes": (specification.name_denotes
                                if specification.name_is_reconstructed else
                                "the static actuator applied to every row; no "
                                "sensor composition to identify"),
                }
                for specification in SYSTEMS},
        },
        "figures": figures,
        "outputs": {
            "note": ("every file this run wrote, except provenance_manifest.json "
                     "itself and the output_hashes.json that covers it; both are "
                     "digested in output_hashes.json"),
            "files": written_before_the_manifest,
        },
        "checklist": checks.as_dict(),
    }
    write_json(output_dir / "provenance_manifest.json", manifest)
    digest_map = write_output_hashes(output_dir)
    say(f"[figures] wrote provenance_manifest.json and output_hashes.json "
        f"({len(digest_map)} output digest(s))")
    say("[figures] done")
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR,
                        help="a new or empty directory; never written over")
    parser.add_argument("--dry-run", action="store_true",
                        help="read, validate and derive everything, and write "
                             "nothing")
    parser.add_argument("--paths-file", type=Path, default=None)
    parser.add_argument("--static-master", type=Path, default=None)
    parser.add_argument("--focused-direction-dir", type=Path, default=None)
    parser.add_argument("--phase2-readings", type=Path, default=None)
    parser.add_argument("--phase2-analysis-table", type=Path, default=None)
    parser.add_argument("--residual-run", type=Path, default=RESIDUAL_RUN)
    parser.add_argument("--routing-run", type=Path, default=ROUTING_RUN)
    parser.add_argument("--probe-run", type=Path, default=PROBE_RUN)
    args = parser.parse_args(argv)

    try:
        # Inside the guard, so a sealed path is refused the way every other
        # bad input is -- one FATAL line and a non-zero exit -- rather than a
        # traceback.
        for value in vars(args).values():
            if isinstance(value, Path):
                assert_not_sealed(value, "command-line path")
        return build(args)
    except ValidationError as exc:
        print(f"[FATAL] {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
