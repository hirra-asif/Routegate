def resolve_sources(args: argparse.Namespace) -> Dict[str, Path]:
    """Every input path, through the repository's own path mechanism."""
    from routegate.data import load_local_paths

    paths = load_local_paths(args.paths_file) if args.paths_file else load_local_paths()

    master = args.static_master or paths.get("static_steering_master")
    if not master:
        raise ThesisResultsError(
            "configs/paths.local.json names no static_steering_master and none "
            "was given with --static-master. The static B-E development results "
            "are read from that file and from nothing else.")

    root = args.focused_direction_dir or paths.get("focused_direction_validation_dir")
    if not root:
        raise ThesisResultsError(
            "configs/paths.local.json names no focused_direction_validation_dir "
            "and none was given with --focused-direction-dir.")
    readings_root = Path(root) / "phase2" / "judging" / "readings"

    sources = {
        "static_steering_master": Path(master),
        "residual_oof_predictions": Path(args.residual_run) / "oof_predictions.csv",
        "residual_thresholds": Path(args.residual_run) / "thresholds.json",
        "routing_oof_predictions": Path(args.routing_run) / "oof_predictions.csv",
        "routing_thresholds": Path(args.routing_run) / "thresholds.json",
        "phase2_readings": args.phase2_readings or readings_root / "phase2_readings.json",
        "phase2_analysis_table": (args.phase2_analysis_table
                                  or readings_root / "analysis_table.jsonl"),
        "probe_metrics": Path(args.probe_run) / "metrics.json",
        "probe_oof_predictions": Path(args.probe_run) / "oof_predictions.csv",
        "probe_validation": Path(args.probe_run) / "validation.json",
        "probe_run_manifest": Path(args.probe_run) / "run_manifest.json",
    }
    for label, path in sources.items():
        assert_source_is_usable(path, label)
    return sources


# ---------------------------------------------------------------- derivation
def derive_everything(sources: Dict[str, Path],
                      checks: Checklist) -> Dict[str, Any]:
    """Read every source, validate it, and derive every reported count."""
    digests = {label: sha256_file(path) for label, path in sources.items()}
    assert_input_digests(digests, EXPECTED_INPUT_DIGESTS, checks)

    outcomes = read_static_steering_master(sources["static_steering_master"], checks)

    residual = read_gate_source(
        "routegate_residual_v1",
        sources["residual_oof_predictions"], sources["residual_thresholds"],
        families=("residual",), prefixed=False,
        recorded_gate_columns={"residual": "gate_full"},
        expected_rows=len(outcomes.rows), checks=checks)
    routing = read_gate_source(
        "routegate_routing_analysis_v1",
        sources["routing_oof_predictions"], sources["routing_thresholds"],
        families=("residual", "routing", "residual+routing"), prefixed=True,
        recorded_gate_columns={"residual": "residual_gate_full"},
        expected_rows=len(outcomes.rows), checks=checks)

    # Corpus membership: the outcome table and both sensor runs must be scoring
    # the same 480 rows, with the same class for each of them.
    for source in (residual, routing):
        checks.require(f"{source.name}_rows_are_the_corpus",
                       set(source.rows) == set(outcomes.rows),
                       f"{len(set(source.rows) ^ set(outcomes.rows))} row id(s) "
                       f"differ between {source.name} and the outcome table")
        mismatched = [r for r in source.classes
                      if r in outcomes.rows
                      and source.classes[r] != outcomes.rows[r]["frozen_class"]]
        checks.require(f"{source.name}_classes_agree_with_the_corpus",
                       not mismatched,
                       f"{len(mismatched)} row(s) carry a different class in "
                       f"{source.name} than in the frozen outcome table")

    # The two runs are two records of the same residual sensor. Neither is
    # preferred: they are required to agree, and both digests are recorded.
    worst = max(abs(residual.rows[r]["p_E"] - routing.rows[r]["residual_p_E"])
                for r in residual.rows)
    worst_h = max(abs(residual.rows[r]["p_H"] - routing.rows[r]["residual_p_H"])
                  for r in residual.rows)
    checks.require("residual_sensor_agrees_across_both_run_records",
                   max(worst, worst_h) < 1e-9,
                   f"max |dp_E| = {worst:.3e}, max |dp_H| = {worst_h:.3e} between "
                   f"routegate_residual_v1 and its re-derivation in "
                   f"routegate_routing_analysis_v1")
    checks.require("residual_thresholds_agree_across_both_run_records",
                   (residual.thresholds["residual"]
                    == routing.thresholds["residual"]),
                   f"{residual.thresholds['residual']} vs "
                   f"{routing.thresholds['residual']}")

    readings: Dict[str, Any] = {}
    for specification in SYSTEMS:
        if specification.kind == "static":
            readings[specification.system_id] = derive_system_reading(
                specification, outcomes, checks=checks)
            continue
        gate = derive_gate(routing, specification.e_family,
                           specification.h_family, prefixed=True)
        thresholds = {
            "threshold_E": routing.thresholds[specification.e_family]["threshold_E"],
            "threshold_H": routing.thresholds[specification.h_family]["threshold_H"],
        }
        if specification.recorded_gate_column is not None:
            # System identity: the derived gate must be the gate both run
            # records already carry, or this is not that system.
            disagreements = [r for r in gate
                             if gate[r] != residual.recorded_gates[r]["residual"]]
            checks.require(
                f"{specification.system_id}_matches_the_recorded_gate",
                not disagreements,
                f"{len(disagreements)} row(s) differ between the gate derived "
                f"from the frozen thresholds and the "
                f"{specification.recorded_gate_column} column of "
                f"routegate_residual_v1")
            disagreements = [r for r in gate
                             if gate[r] != routing.recorded_gates[r]["residual"]]
            checks.require(
                f"{specification.system_id}_matches_the_reproduced_gate",
                not disagreements,
                f"{len(disagreements)} row(s) differ between the derived gate "
                f"and residual_gate_full in routegate_routing_analysis_v1")
        else:
            checks.record(
                f"{specification.system_id}_has_no_recorded_gate_column", True,
                "no run record carries this gate as a column; it is derived "
                "from the frozen out-of-fold probabilities and the frozen "
                "thresholds, and the derivation is what the manifest records")
        readings[specification.system_id] = derive_system_reading(
            specification, outcomes, steered=gate, thresholds=thresholds,
            checks=checks)

    phase2_readings = read_phase2_readings(sources["phase2_readings"], checks)
    verdicts = read_phase2_analysis_table(sources["phase2_analysis_table"], checks)
    screen = derive_phase2_screen(verdicts, phase2_readings, checks)
    assert_screen_matches_readings(screen, phase2_readings, checks)
    matrix = derive_failure_matrix(phase2_readings, checks)
    assert_failure_matrix_matches_screen(matrix, screen, checks)

    assert_frozen_checkpoints(readings, screen, outcomes.class_sizes(), checks)

    # The out-of-fold probe heads. A separate frozen run, read the same way:
    # its stored metrics are what gets reported, its stored predictions are
    # read to check them and to bin the calibration the run did not store.
    probe_metrics = read_probe_metrics(sources["probe_metrics"], checks)
    probe_validation = read_probe_validation(sources["probe_validation"], checks)
    read_probe_run_manifest(sources["probe_run_manifest"], digests, checks)
    probe_predictions = read_probe_oof_predictions(
        sources["probe_oof_predictions"], checks)
    probes = derive_probe_readings(probe_metrics, probe_validation,
                                   probe_predictions, checks)
    checks.require(
        "probe_class_counts_agree_with_the_corpus",
        probes.class_counts == outcomes.class_sizes(),
        f"the probe run scored {probes.class_counts}; the outcome table holds "
        f"{outcomes.class_sizes()}")
    assert_probe_checkpoints(probes, checks)

    return {"digests": digests, "outcomes": outcomes, "readings": readings,
            "screen": screen, "matrix": matrix, "probes": probes,
            "phase2_readings": phase2_readings,
            "sensor_runs": {"routegate_residual_v1": residual,
                            "routegate_routing_analysis_v1": routing}}


# ------------------------------------------------------------------ figures
def _title_block(fig, title: str, subtitle: str, *, wrap: int = 116,
                 title_size: float = 12.6, reserve: float = 0.0) -> float:
    """Title over a wrapped subtitle in a reserved header band.

    Returns the ``top`` fraction the axes must stay below. Laid out in inches
    against the figure height rather than by ``tight_layout``, which cannot
    make room for text it does not own and silently gives up on a long one.
    ``reserve`` is the extra height, in inches, that the axes will themselves
    draw above their own box -- a panel title and its pad, say -- which the
    header has to clear as well.
    """
    import textwrap

    lines: List[str] = []
    for chunk in subtitle.split("\n"):
        lines.extend(textwrap.wrap(chunk, width=wrap) or [""])
    height = fig.get_size_inches()[1]
    fig.text(0.012, 1.0 - 0.30 / height, title, ha="left", va="top",
             fontsize=title_size, color=plotting.INK)
    fig.text(0.012, 1.0 - 0.62 / height, "\n".join(lines), ha="left", va="top",
             fontsize=8.5, color=plotting.INK_SECONDARY, linespacing=1.55)
    return 1.0 - (0.80 + 0.185 * len(lines) + reserve) / height


def _maths(label: str) -> str:
    """Render the greek a plain-text field spells out.

    The specifications hold plain names -- they are also written into the
    manifest and the CSV tables, where mathtext would be noise -- so the
    substitution happens here, at the one place that is drawing them.
    """
    return label.replace("alpha_R", "$\\alpha_R$").replace("alpha_S", "$\\alpha_S$")


def _nice_ticks(top: float) -> List[float]:
    """At most six ticks on a round step that covers ``top``."""
    for step in (0.01, 0.02, 0.025, 0.05, 0.1, 0.2, 0.25, 0.5, 1.0):
        if top / step <= 5.001:
            break
    count = int(top / step) + (0 if abs(top / step - round(top / step)) < 1e-9 else 1)
    return [index * step for index in range(count + 1)]


def _percent_axis(axis, ticks: Sequence[float], headroom: float = 1.17) -> None:
    axis.set_yticks(list(ticks))
    axis.set_yticklabels([f"{tick * 100:.0f}%" for tick in ticks])
    axis.set_ylim(0.0, max(ticks) * headroom)


def figure_1(readings: Dict[str, Any], directory: Path, plt) -> Dict[str, str]:
    """Repair against damage, three systems, one panel per class."""
    order = [specification.system_id for specification in SYSTEMS]
    names = [_maths(specification.short_name) for specification in SYSTEMS]

    damage_top = max(readings[system_id].proportions[label].interval[1]
                     for system_id in order for label in ("B", "H"))
    ticks = {"E": _nice_ticks(1.0), "B": _nice_ticks(damage_top),
             "H": _nice_ticks(damage_top)}

    fig = plt.figure(figsize=(11.4, 6.0))
    top = _title_block(
        fig,
        "Repair against damage on the development corpus",
        "Development results only; the sealed set is untouched. Every "
        "denominator is the whole class, so a row a gate did not fire on is a "
        "denominator row that keeps its baseline outcome rather than a row "
        "removed from the comparison. Bars carry n/N and the percentage; "
        "whiskers are Wilson 95% intervals. Panels B and C share a scale, "
        "panel A does not.",
        wrap=132, reserve=0.62)
    axes = fig.subplots(1, 3)
    fig.subplots_adjust(left=0.070, right=0.988, bottom=0.150, top=top,
                        wspace=0.34)

    for axis, label in zip(axes, DEVELOPMENT_CLASSES):
        definition = METRIC_DEFINITIONS[label]
        colour = plotting.CLASS_COLOURS[label]
        span = max(ticks[label])
        for index, system_id in enumerate(order):
            proportion = readings[system_id].proportions[label]
            low, high = proportion.interval
            axis.bar(index, proportion.rate, width=0.54, color=colour,
                     edgecolor=plotting.SURFACE, linewidth=1.6, zorder=3)
            axis.plot([index, index], [low, high], color=plotting.INK_SECONDARY,
                      linewidth=1.3, solid_capstyle="butt", zorder=4)
            for end in (low, high):
                axis.plot([index - 0.085, index + 0.085], [end, end],
                          color=plotting.INK_SECONDARY, linewidth=1.3, zorder=4)
            axis.text(index, high + span * 0.030,
                      f"{proportion.numerator}/{proportion.denominator}\n"
                      f"{100.0 * proportion.rate:.1f}%",
                      ha="center", va="bottom", fontsize=8.6, linespacing=1.3,
                      color=plotting.INK_SECONDARY, zorder=5)
        axis.set_xticks(range(len(order)))
        axis.set_xticklabels(names, fontsize=8.2)
        axis.set_xlim(-0.66, len(order) - 0.34)
        _percent_axis(axis, ticks[label])
        axis.set_title(f"{definition['panel']}.  {definition['title']}",
                       loc="left", fontsize=10.6, pad=19)
        axis.text(0.0, 1.012, definition["direction"], transform=axis.transAxes,
                  ha="left", va="bottom", fontsize=8.4, color=plotting.INK_MUTED)
        plotting.tidy(axis)
    axes[0].set_ylabel("rate over the whole class")
    return plotting.save_figure(fig, directory, FIGURE_STEMS[1])


def figure_2(screen, directory: Path, plt) -> Dict[str, str]:
    """The phase-2 causal screen: recovery against harm caused alone."""
    positions = list(range(len(PHASE2_STRENGTHS)))
    recovered = [screen.recovered[s].numerator for s in PHASE2_STRENGTHS]
    harmful = [screen.harmful_alone[s].numerator for s in PHASE2_STRENGTHS]
    n = screen.denominator
    gutter = len(positions) - 0.30           # empty band the line labels sit in

    fig = plt.figure(figsize=(9.8, 6.0))
    top = _title_block(
        fig,
        f"Phase 2 causal screen: outcome {screen.outcome}",
        f"A targeted {n}-row causal follow-up, not a population safety rate: "
        f"these rows were selected because they regressed under the repair "
        f"direction at $\\alpha_R$ = 0.15, so no count here may be divided by "
        f"any corpus denominator. A strength qualifies only if it clears both "
        f"frozen lines, and none does. $d_S$ = H - E is retired as an ACTUATOR "
        f"only: the H-versus-(E+B) probe is retained as a sensor and brake.",
        wrap=112, reserve=0.10)
    axis = fig.subplots()
    fig.subplots_adjust(left=0.085, right=0.985, bottom=0.185, top=top)

    width = 0.32
    series = (
        (plotting.SERIES_B, recovered, -width / 2 - 0.014,
         f"recovered under repair + safety steering (of {n})"),
        (plotting.STATUS_CRITICAL, harmful, width / 2 + 0.014,
         f"made harmful by safety steering alone (of {n})"),
    )
    for colour, values, offset, label in series:
        bars = axis.bar([p + offset for p in positions], values, width=width,
                        color=colour, edgecolor=plotting.SURFACE, linewidth=1.6,
                        zorder=3, label=label)
        for bar, value in zip(bars, values):
            axis.text(bar.get_x() + bar.get_width() / 2, value + 0.22,
                      f"{value}/{n}", ha="center", va="bottom", fontsize=9.0,
                      color=plotting.INK_SECONDARY, zorder=5)

    axis.axhline(screen.recovery_threshold, color=plotting.SERIES_B,
                 linewidth=1.3, linestyle=(0, (5, 3)), zorder=2)
    axis.text(gutter + 0.12, screen.recovery_threshold + 0.30,
              f"frozen minimum recovery\n{screen.recovery_threshold} of {n}",
              ha="left", va="bottom", fontsize=8.6, linespacing=1.4,
              color=plotting.SERIES_B)
    axis.axhline(screen.safety_only_harm_limit, color=plotting.STATUS_CRITICAL,
                 linewidth=1.7, zorder=2)
    axis.text(gutter + 0.12, screen.safety_only_harm_limit + 0.30,
              f"zero-failure safety veto\n{screen.safety_only_harm_limit} of {n}",
              ha="left", va="bottom", fontsize=8.6, linespacing=1.4,
              color=plotting.STATUS_CRITICAL)

    for index, strength in enumerate(PHASE2_STRENGTHS):
        entry = screen.per_strength[strength]
        reasons = []
        if not entry["meets_recovery_threshold"]:
            reasons.append("recovery short")
        if not entry["causes_no_harm_alone"]:
            reasons.append("veto tripped")
        axis.text(index, -1.45, " + ".join(reasons) or "qualifies",
                  ha="center", va="top", fontsize=8.2,
                  color=plotting.STATUS_CRITICAL if reasons else plotting.INK_MUTED)

    axis.set_xticks(positions)
    axis.set_xticklabels([f"$\\alpha_S$ = {s}" for s in PHASE2_STRENGTHS])
    axis.set_yticks(range(0, n + 1, 3))
    axis.set_ylim(0, n)
    axis.set_ylabel(f"rows, of the {n} selected")
    axis.set_xlim(-0.62, gutter + 1.62)
    axis.legend(loc="upper left", fontsize=9.0)
    plotting.tidy(axis)
    return plotting.save_figure(fig, directory, FIGURE_STEMS[2])


def figure_3(matrix, screen, directory: Path, plt) -> Dict[str, str]:
    """Which rows the safety direction made harmful on its own, and where."""
    labels = list(matrix.labels)
    columns = len(matrix.strengths)

    fig = plt.figure(figsize=(7.6, 2.05 + 0.72 * len(labels)))
    top = _title_block(
        fig,
        "Safety-only failure matrix",
        f"Every row adjudicated actionable-harmful YES under the safety "
        f"direction alone, with no repair applied, at any strength -- "
        f"{len(labels)} of the {screen.denominator} selected rows. Labels are "
        f"deterministic anonymisations ordered by failure count then row id; "
        f"they carry no source identity, and the mapping to source rows is "
        f"kept in the provenance manifest, not on this figure. One YES "
        f"anywhere trips the zero-failure veto.",
        wrap=88, title_size=12.0, reserve=0.10)
    axis = fig.subplots()
    fig.subplots_adjust(left=0.105, right=0.985, bottom=0.135, top=top)

    for row, label in enumerate(labels):
        for column, strength in enumerate(matrix.strengths):
            failed = matrix.failed[label][column]
            axis.add_patch(plt.Rectangle(
                (column - 0.33, row - 0.34), 0.66, 0.68,
                facecolor=plotting.STATUS_CRITICAL if failed else plotting.SURFACE,
                edgecolor=plotting.STATUS_CRITICAL if failed else plotting.AXIS,
                linewidth=1.1, zorder=3))
            axis.text(column, row, "YES" if failed else "no", ha="center",
                      va="center", fontsize=8.6, zorder=4,
                      color=plotting.SURFACE if failed else plotting.INK_MUTED)
        axis.text(columns - 0.46, row,
                  f"{matrix.failure_counts[label]} of {columns}",
                  ha="left", va="center", fontsize=8.6,
                  color=plotting.INK_SECONDARY)

    axis.text(columns - 0.46, -0.78, "strengths\nfailed", ha="left", va="center",
              fontsize=8.4, linespacing=1.35, color=plotting.INK_MUTED)
    axis.set_xticks(range(columns))
    axis.set_xticklabels([f"$\\alpha_S$ = {s}" for s in matrix.strengths])
    axis.set_yticks(range(len(labels)))
    axis.set_yticklabels(labels)
    axis.set_xlim(-0.62, columns + 0.46)
    axis.set_ylim(len(labels) - 0.42, -1.10)
    axis.grid(False)
    for side in ("top", "right", "bottom", "left"):
        axis.spines[side].set_visible(False)
    axis.tick_params(length=0)
    return plotting.save_figure(fig, directory, FIGURE_STEMS[3])


def figure_4(probes, directory: Path, plt) -> Dict[str, str]:
    """Two reliability panels, each over its own bin-count histogram.

    The histogram is not decoration. Marker area alone cannot be read back to
    a count, and a reliability curve drawn without one invites a reader to give
    a bin of two rows the same weight as a bin of two hundred. It also makes an
    empty bin *visible* -- a bin with no marker above it and a zero bar below
    it, still occupying its place on the axis -- rather than a silent gap.

    The primary read state only. States 33 and 34 are sensitivity rows in the
    table and are deliberately not drawn: a second panel pair would invite a
    reader to pick the state whose curve looks best, which is the choice the
    predeclaration exists to prevent.
    """
    fig = plt.figure(figsize=(10.4, 6.6))
    top = _title_block(
        fig,
        f"Out-of-fold probe calibration, state {probes.primary_state}",
        f"Uncalibrated out-of-fold probabilities from the frozen probe-head "
        f"run, read at state {probes.primary_state} (the output of historical "
        f"decoder block {probes.primary_layer}) at the final prompt token. "
        f"State {probes.primary_state} was predeclared before either head was "
        f"fitted; states "
        f"{', '.join(str(s) for s in probes.sensitivity_states)} are "
        f"sensitivity rows in Table 4 and no state is selected here. Ten "
        f"fixed equal-width bins, plotted at the mean predicted probability "
        f"in the bin; the lower panel gives each bin's row count on the same "
        f"axis, so an empty bin keeps its place. No calibration model is "
        f"fitted and none is applied.",
        wrap=118, reserve=0.52)
    axes = fig.subplots(2, 1 * 2, sharex="col", height_ratios=(3.0, 1.0))
    fig.subplots_adjust(left=0.070, right=0.988, bottom=0.112, top=top,
                        wspace=0.175, hspace=0.10)

    colours = {"repair": plotting.SERIES_E, "safety": plotting.SERIES_H}
    panels = {"repair": "A", "safety": "B"}
    for column, head in enumerate(PROBE_HEADS):
        upper, lower = axes[0][column], axes[1][column]
        reading = probes.primary[head]
        colour = colours[head]
        filled = [b for b in reading.bins if not b.is_empty]
        biggest = max(b.count for b in filled)

        # ---- reliability
        upper.plot([0, 1], [0, 1], color=plotting.INK_MUTED, linewidth=1.1,
                   linestyle=(0, (4, 3)), zorder=2, label="perfect calibration")
        upper.plot([b.mean_predicted for b in filled],
                   [b.observed_fraction for b in filled],
                   color=colour, linewidth=1.5, zorder=3, alpha=0.5)
        upper.scatter([b.mean_predicted for b in filled],
                      [b.observed_fraction for b in filled],
                      s=[40.0 + 260.0 * (b.count / biggest) for b in filled],
                      facecolor=colour, edgecolor=plotting.SURFACE,
                      linewidth=1.6, zorder=4, label="bin, area = row count")
        upper.set_xlim(-0.04, 1.04)
        upper.set_ylim(-0.04, 1.06)
        upper.set_yticks([0.0, 0.25, 0.5, 0.75, 1.0])
        # No equal aspect: the box has to keep the x extent of the count panel
        # under it, and a square reliability plot would shrink away from it.
        # The diagonal is drawn, so "on the diagonal" stays readable regardless.
        plotting.tidy(upper)

        task = PROBE_HEAD_TASKS[head]
        upper.set_title(f"{panels[head]}.  {head} head — {task['task']}",
                        loc="left", fontsize=10.6, pad=19)
        empty = [b.label for b in reading.bins if b.is_empty]
        upper.text(0.0, 1.012,
                   f"n = {reading.n_scored} ({reading.n_positive}+ / "
                   f"{reading.n_negative}−) · Brier {reading.brier:.4f} · "
                   f"ECE {reading.ece:.4f} · "
                   + (f"empty: {', '.join(empty)}" if empty
                      else "no empty bin"),
                   transform=upper.transAxes, ha="left", va="bottom",
                   fontsize=7.9, color=plotting.INK_MUTED)
        upper.legend(loc="upper left", fontsize=8.4)

        # ---- bin counts, on the same probability axis
        centres = [(b.low + b.high) / 2.0 for b in reading.bins]
        counts = [b.count for b in reading.bins]
        lower.bar(centres, counts, width=0.088, color=colour, alpha=0.82,
                  edgecolor=plotting.SURFACE, linewidth=1.2, zorder=3)
        headroom = max(counts) * 1.34
        for centre, count in zip(centres, counts):
            lower.text(centre, count + max(counts) * 0.055, str(count),
                       ha="center", va="bottom", fontsize=7.8, zorder=4,
                       color=(plotting.INK_MUTED if count == 0
                              else plotting.INK_SECONDARY))
        lower.set_ylim(0, headroom)
        lower.set_yticks([0, max(counts)])
        lower.set_xlim(-0.04, 1.04)
        lower.set_xticks([0.0, 0.25, 0.5, 0.75, 1.0])
        lower.set_xlabel("uncalibrated OOF probability\n"
                         "(upper: bin mean; lower: ten fixed bins)")
        plotting.tidy(lower)

    axes[0][0].set_ylabel("observed positive fraction in bin")
    axes[1][0].set_ylabel("rows")
    return plotting.save_figure(fig, directory, FIGURE_STEMS[4])


