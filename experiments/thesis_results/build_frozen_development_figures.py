#!/usr/bin/env python3
"""Build the frozen development figures and tables for the thesis results.

Offline and deterministic. Loads no model, generates nothing, judges nothing,
fits nothing, calls no service and never reads the sealed set. It reads
completed, hash-checked result files, derives every count from the records in
them, and writes a figure directory that can be regenerated byte-for-byte from
the same inputs.

What it reads
-------------
=========================  ====================================================
static steering master     per-row adjudicated outcomes of the static B-E
                           actuator at ``alpha_R = 0.15``, over all 480
                           development rows
routegate_residual_v1      out-of-fold sensor probabilities and the frozen
                           threshold rules for the residual family
routegate_routing_...v1    the same, re-derived per family, and the only record
                           carrying the residual+routing H veto
phase2 readings            the completed phase-2 causal screen
phase2 analysis table      the 180 per-cell adjudicated safety verdicts the
                           screen was counted from
=========================  ====================================================

The first is resolved through ``configs/paths.local.json`` -- the one place a
machine-local absolute path appears -- as are the two phase-2 files, via the
focused-direction data root. The two sensor runs are repository run records and
are resolved from the repository. Every one of them is SHA-256'd, checked
against the digest this derivation was written for, and recorded.

What it writes
--------------
Three figures as high-resolution PNG and editable SVG, three CSV tables, a
booktabs LaTeX file, a Markdown results section with thesis-ready captions, and
``provenance_manifest.json`` carrying the git state, every input digest, every
output digest, every derived count and the full validation checklist.

Nothing is typed in as data. The known counts live in
``routegate.thesisresults.FROZEN_CHECKPOINTS`` and are compared to the
derivation after it has run; if any of them disagrees, this refuses to write.

Usage
-----
    python experiments/thesis_results/build_frozen_development_figures.py --dry-run
    python experiments/thesis_results/build_frozen_development_figures.py \\
        --output-dir outputs/thesis_results/frozen_development_figures_v1
"""
